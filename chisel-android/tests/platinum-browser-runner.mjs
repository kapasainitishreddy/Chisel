import fs from 'node:fs';
import puppeteer from 'puppeteer-core';
const base=process.argv[2]||'http://127.0.0.1:4173';
const out='/tmp/chisel-platinum';fs.mkdirSync(out,{recursive:true});
const report={scope:'Real rendered UI, keyboard navigation and invalid-upload handling. No camera accuracy or photoreal output certification.',checks:[],errors:[],screens:[]};
let browser;
function check(name,passed,detail){report.checks.push({name,passed:!!passed,detail});}
try{
 browser=await puppeteer.launch({executablePath:process.env.CHROME,headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader']});
 const page=await browser.newPage();
 await page.setViewport({width:430,height:900,deviceScaleFactor:1});
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
 page.on('pageerror',e=>report.errors.push(String(e.message||e)));
 await page.goto(`${base}/www/index.html`,{waitUntil:'load',timeout:30000});
 await page.waitForFunction(()=>document.documentElement.dataset.chiselPlatinum==='1',{timeout:20000});
 await page.waitForSelector('#idModal.on',{visible:true,timeout:10000});
 await page.click('#idX');
 await page.waitForFunction(()=>!document.getElementById('idModal').classList.contains('on'));
 check('Page title and theme',await page.evaluate(()=>document.title.includes('Chisel')&&document.documentElement.dataset.chiselTheme==='platinum'));
 check('Pinch zoom allowed',await page.evaluate(()=>!document.querySelector('meta[name="viewport"]').content.includes('user-scalable=no')));
 check('No floating launchers',await page.evaluate(()=>['chiselLabsLauncher','chiselPrecisionLauncher'].every(id=>getComputedStyle(document.getElementById(id)).display==='none')));
 const screenshot=async(name,width)=>{await page.screenshot({path:`${out}/${name}-${width}.png`});report.screens.push(`${name}-${width}.png`);};
 const nav=async(route,width)=>{const selector=`${width<=760?'#bottomTabs':'nav.rail'} [data-route="${route}"]`;await page.click(selector);await page.waitForFunction(r=>document.querySelector('.screen.active').dataset.screen===r,{},route);};
 const fits=async(selector)=>page.evaluate(sel=>{const n=document.querySelector(sel);if(!n)return false;const r=n.getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1&&n.scrollWidth<=n.clientWidth+1;},selector);
 for(const width of [430,360,320,1280]){
  await page.setViewport({width,height:900,deviceScaleFactor:1});
  await nav('home',width);
  await page.evaluate(()=>document.querySelector('main.view').scrollTop=0);
  check(`Home fits ${width}`,await fits('[data-screen="home"]'));
  await screenshot('home',width);
  await page.click('#openSettings');
  check(`Settings action ${width}`,await page.evaluate(()=>document.querySelector('.screen.active').dataset.screen==='connect'));
  await nav('analyze',width);
  await page.evaluate(()=>document.querySelector('main.view').scrollTop=0);
  check(`Analyze fits ${width}`,await fits('[data-screen="analyze"]'));
  const controls=await page.evaluate(()=>['openAnalyze','openTrain'].map(id=>{const b=document.getElementById(id),s=getComputedStyle(b),r=b.getBoundingClientRect();return{height:r.height,font:parseFloat(s.fontSize),radius:s.borderRadius,spacing:s.letterSpacing};}));
  check(`Consistent readable scan buttons ${width}`,controls.every(c=>c.height>=48&&c.font>=14&&c.radius==='12px'),controls);
  await screenshot('analyze',width);
  await page.click('#openTrain');
  await page.waitForSelector('#arCoachModal.on',{visible:true});
  check(`Trainer fits ${width}`,await fits('#arCoachModal .panel'));
  const sessions=await page.evaluate(()=>[...document.querySelectorAll('#arCoachModal .ar-session')].map(b=>({h:b.getBoundingClientRect().height,font:parseFloat(getComputedStyle(b.querySelector('strong')).fontSize)})));
  check(`Six readable sessions ${width}`,sessions.length===6&&sessions.every(c=>c.h>=48&&c.font>=14),sessions);
  check(`Pinned close ${width}`,await page.evaluate(()=>{const r=document.getElementById('arCoachX').getBoundingClientRect();return r.width>=48&&r.height>=48&&r.top>=0&&r.bottom<innerHeight;}));
  check(`Reduced motion ${width}`,await page.evaluate(()=>getComputedStyle(document.querySelector('#arCoachModal .panel')).animationName==='none'));
  await screenshot('trainer',width);
  await page.click('#cpTrainerDetails > summary');
  check(`Trainer evidence accessible ${width}`,await page.evaluate(()=>document.getElementById('cpTrainerDetails').open&&document.querySelector('#arCoachModal .ctv2-trust').getBoundingClientRect().height>0));
  await page.click('#cpTrainerDetails > summary');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.getElementById('arCoachModal').classList.contains('on'));
  check(`Trainer focus restored ${width}`,await page.evaluate(()=>document.activeElement.id==='openTrain'&&!document.querySelector('.app').inert));
  await page.click('[data-cp-tool="skin"]');
  await page.waitForSelector('#csaShell',{visible:true});
  check(`Skin fits ${width}`,await fits('#csaShell'));
  check(`Skin starts without invented values ${width}`,await page.evaluate(()=>document.getElementById('csaResults').hidden&&document.getElementById('csaAnalyze').disabled));
  await screenshot('skin',width);
  await page.click('#cpSkinPreferences > summary');
  await page.click('#chl-skin-sensitive');
  check(`Skin preferences interactive ${width}`,await page.evaluate(()=>document.getElementById('chl-skin-sensitive').checked));
  await page.click('#chl-skin-sensitive');
  await page.click('#cpSkinPreferences > summary');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.getElementById('chiselLabsRoot').hidden);
  check(`Skin focus restored ${width}`,await page.evaluate(()=>document.activeElement.dataset.cpTool==='skin'));
  await page.click('[data-cp-tool="precision"]');
  await page.waitForSelector('#chiselPrecisionRoot:not([hidden])',{visible:true});
  check(`Precision remains reachable ${width}`,await page.evaluate(()=>!document.getElementById('chiselPrecisionRoot').hidden));
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.getElementById('chiselPrecisionRoot').hidden);
  await nav('groom',width);
  await page.evaluate(()=>document.querySelector('main.view').scrollTop=0);
  check(`Style fits ${width}`,await fits('#cxStudioCard'));
  check(`All unisex style actions retained ${width}`,await page.evaluate(()=>document.querySelectorAll('#cxStudioCard [data-cx]').length===4));
  await screenshot('style',width);
 }
 await page.setViewport({width:430,height:900,deviceScaleFactor:1});
 await nav('analyze',430);await page.click('[data-cp-tool="skin"]');
 fs.writeFileSync(`${out}/invalid-photo.txt`,'Not an image');
 await(await page.$('#csaFile')).uploadFile(`${out}/invalid-photo.txt`);
 check('Invalid image does not produce results',await page.evaluate(()=>document.getElementById('csaResults').hidden&&document.getElementById('csaAnalyze').disabled&&/JPEG|PNG|WebP/i.test(document.getElementById('csaStatus').textContent)));
 await page.keyboard.press('Escape');
 await page.evaluate(()=>openTrain());
 await page.waitForSelector('#arCoachModal.on',{visible:true});
 await page.focus('#arCoachX');await page.keyboard.down('Shift');await page.keyboard.press('Tab');await page.keyboard.up('Shift');
 check('Keyboard focus stays in trainer',await page.evaluate(()=>document.getElementById('arCoachModal').contains(document.activeElement)));
 await page.keyboard.press('Escape');
 check('No uncaught application errors',report.errors.length===0);
 if(report.checks.some(c=>!c.passed))throw new Error('Platinum UI checks failed: '+report.checks.filter(c=>!c.passed).map(c=>c.name).join(', '));
}catch(error){report.errors.push(String(error.stack||error));process.exitCode=1;}
finally{fs.writeFileSync(`${out}/report.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));if(browser)await browser.close();}
